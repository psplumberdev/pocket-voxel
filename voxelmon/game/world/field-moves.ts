export function fieldCells(x: number, y: number, facing: Dir, area: "melee" | "forward" | "self"): [number, number][] {
  const dx = facing === "left" ? -1 : facing === "right" ? 1 : 0;
  const dy = facing === "up" ? -1 : facing === "down" ? 1 : 0;
  if (area === "forward") return [1, 2, 3, 4].map(n => [x + dx*n, y + dy*n]);
  const cells: [number, number][] = [];
  const radius = area === "self" ? 3 : 1;
  for (let oy = -radius; oy <= radius; oy++) for (let ox = -radius; ox <= radius; ox++) {
    if (area === "self" ? ox*ox + oy*oy <= 9 : (ox !== 0 || oy !== 0) && ox*dx + oy*dy >= 0) cells.push([x + ox, y + oy]);
  }
  return cells;
}
